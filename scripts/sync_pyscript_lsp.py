"""Pull the pyScript Python stdlib sources locally for LSP support.

pyScript's `pyscript.*` modules (`web`, `when`, `fetch`, `ffi`, …) only exist
inside the browser runtime, so editors/`pyright` can't resolve them from the
server environment. This script:

1. reads the pinned pyScript release from `<app-root>/pyscript.version`
2. downloads that tag's interpreter stdlib (`core/src/stdlib/pyscript/**.py`
   from the pyScript repo) into `<app-root>/packages/lsp/pyscript/`
3. writes `<app-root>/packages/lsp/pyrightconfig.json` with `extraPaths`
   pointing there — point Pyright/Pylance/YourLSP at that directory (or copy
   the file to the project root) and `from pyscript import web` resolves with
   real types, straight from the pinned release.

CLI:
    python senza/utils/sync_pyscript_lsp.py            # sync for pinned version
    python senza/utils/sync_pyscript_lsp.py --root <app-root>
"""

import json
import sys
import urllib.request
from pathlib import Path
from typing import Optional, Union

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

StrPath = Union[str, Path]
# the stdlib sources for a pyscript tag, discovered via the git tree API
STDLIB_PREFIX = "core/src/stdlib/pyscript/"
TREE_URL = "https://api.github.com/repos/pyscript/pyscript/git/trees/{tag}?recursive=1"
RAW_URL = "https://raw.githubusercontent.com/pyscript/pyscript/{tag}/{path}"


def _pinned_pyscript(root: Optional[StrPath] = None) -> str:
    root = Path(root).resolve() if root else Path.cwd().resolve()
    for candidate in (root, *root.parents):
        pin = candidate / "pyscript.version"
        if pin.is_file():
            return pin.read_text().strip()
    raise FileNotFoundError("pyScript pin file (pyscript.version) not found — run from an app checkout")


def _symlink(link_path: Path, target: Path) -> str:
    """Create a root-relative symlink for LSP resolution; graceful when the
    path already exists as a real directory (e.g. a senza checkout or
    submodule), and replaces broken/stale symlinks."""
    if link_path.is_symlink():
        current = link_path.resolve()
        if current == target.resolve() and current.exists():
            return "already linked"
        link_path.unlink()  # stale/broken symlink: replace it
        link_path.symlink_to(target, target_is_directory=True)
        return f"relinked -> {target.relative_to(link_path.parent)}"
    if link_path.exists():
        return "exists as a real directory; left alone"
    link_path.symlink_to(target, target_is_directory=True)
    return f"linked -> {target.name}"


def sync(app_root: Optional[StrPath] = None) -> Path:
    """Download the pinned release's pyscript stdlib + write the LSP config.

    Also creates root-relative symlinks (`pyscript`, and `senza` when no real
    senza directory is present) pointing into packages/, so editors resolve
    `from pyscript import web` / `from senza import Router` at the project root.
    """
    root = Path(app_root).resolve() if app_root else Path.cwd().resolve()
    version = _pinned_pyscript(root)

    # what files exist for this tag?
    tree_url = TREE_URL.format(tag=version)
    req = urllib.request.Request(tree_url, headers={"Accept": "application/json"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        tree = json.load(resp)
    module_paths = [
        entry["path"]
        for entry in tree.get("tree", [])
        if entry.get("type") == "blob"
        and entry["path"].startswith(STDLIB_PREFIX)
        and entry["path"].endswith(".py")
    ]
    if not module_paths:
        raise RuntimeError(f"no stdlib modules found for pyscript {version}")

    out_dir = root / "packages" / "lsp"
    pyscript_pkg = out_dir / "pyscript"
    if pyscript_pkg.exists():
        import shutil

        shutil.rmtree(pyscript_pkg)  # pins change -> stale sources must go
    for path in module_paths:  # e.g. core/src/stdlib/pyscript/web.py
        rel = path[len(STDLIB_PREFIX):]
        target = pyscript_pkg / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(RAW_URL.format(tag=version, path=path), timeout=30) as resp:
            target.write_bytes(resp.read())

    config = {
        "comment": (
            f"generated by senza/utils/sync_pyscript_lsp.py — extraPaths resolve "
            f"the browser-only pyScript modules ({version}) and the senza modules"
        ),
        "extraPaths": [pyscript_pkg.as_posix()],
    }
    messages: list[str] = []

    senza_pkg = root / "packages" / "senza"
    if senza_pkg.is_dir():
        config["extraPaths"].append(root.as_posix())  # packages/ is the served copy
        messages.append(f"senza LSP path -> {senza_pkg} (run senza/sync_senza.py to refresh it)")

    # root-level symlinks so LSP resolves `import pyscript` / `import senza`
    messages.append(_symlink(root / "pyscript", pyscript_pkg))
    if senza_pkg.is_dir():
        messages.append(_symlink(root / "senza", senza_pkg))

    (out_dir / "pyrightconfig.json").write_text(json.dumps(config, indent=2))
    print(f"synced pyscript {version} stdlib -> {pyscript_pkg} ({len(module_paths)} modules)")
    for message in messages:
        print(message)
    print(f"LSP config -> {out_dir / 'pyrightconfig.json'}")
    return out_dir


if __name__ == "__main__":
    argv = sys.argv[1:]
    app_root = argv[argv.index("--root") + 1] if "--root" in argv else None
    sync(app_root)